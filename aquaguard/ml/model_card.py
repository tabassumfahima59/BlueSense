"""Render docs/MODEL_CARD.md from ml/artifacts (metrics.json, model_meta.json, split.json).

    python ml/model_card.py

The metrics table is generated, never typed by hand, so the card always matches the evaluation output.
"""
from __future__ import annotations

import json

from common import ARTIFACTS, ROOT

NAMES = {"climatology": "Climatology (baseline)", "persistence": "Persistence (baseline)",
         "random_forest": "Random Forest", "xgboost": "XGBoost"}


def main() -> None:
    met = json.loads((ARTIFACTS / "metrics.json").read_text(encoding="utf-8"))
    meta = json.loads((ARTIFACTS / "model_meta.json").read_text(encoding="utf-8"))
    split = json.loads((ARTIFACTS / "split.json").read_text(encoding="utf-8"))
    lines = [
        "# Model card — AquaGuard scarcity forecast",
        "",
        "_Generated by `ml/model_card.py` from `ml/artifacts/metrics.json`; do not edit by hand._",
        "",
        "## What it predicts",
        "The monthly **climatic water balance D = P − ET0 (mm/month)** per division, 1, 3 and 6 months ahead. "
        "P and ET0 come from ERA5 reanalysis (Open-Meteo, one point per division). D is a measurable quantity; "
        "AquaGuard does not train on a synthetic 'scarcity index'.",
        "",
        "## Data and split",
        f"- Data period: {split['dataPeriod']} (8 divisions, monthly).",
        f"- Split by target date, never random: {split['rule']}.",
        "- Samples per horizon: " + "; ".join(f"h={h}: train {c['train']}, validation {c['validation']}, test {c['test']}"
                                             for h, c in split["counts"].items()) + ".",
        f"- Trained: {meta['trainedAt']}. Evaluated: {met['generatedAt']}.",
        "- Features (no information from the forecast period): lags 0–11 of P, ET0 and D; Tmean lags 0–2; soil moisture "
        "(ERA5-Land model data); rolling means; D anomaly vs training-period climatology; target-month sin/cos; "
        "training-period normal and spread of D for the target month; division id.",
        "",
        "## Models",
        "Random Forest and XGBoost are fit on the training years; the one with the lower validation RMSE is kept, refit on "
        "train + validation and scored on the test years. The operational model is then refit on all labelled data. "
        "Baselines: climatology (training-period mean of that month) and persistence (last observed D).",
        "",
        "## Test-period metrics",
        "",
        "| Horizon | Test period | n | Model | MAE (mm) | RMSE (mm) | R² |",
        "|---|---|---|---|---|---|---|",
    ]
    for h, v in met["horizons"].items():
        for k, r in v["regression"].items():
            sel = " **(selected)**" if k == v["selectedModel"] else ""
            row = [f"{h} mo", v["testPeriod"], v["samples"], f"{NAMES[k]}{sel}", r["mae"], r["rmse"], r["r2"]]
            lines.append("| " + " | ".join(str(x) for x in row) + " |")
    lines += ["", "| Horizon | Dryness-class macro-F1 | Climatology macro-F1 | 90% interval test coverage |", "|---|---|---|---|"]
    for h, v in met["horizons"].items():
        c = v["classification"]
        lines.append(f"| {h} mo | {c['macroF1']} | {c['macroF1Climatology']} | {v['interval']['testCoverage']} |")
    lines += [
        "",
        "## Reading these numbers honestly",
        "- The selected model improves on climatology only modestly at 1 month and roughly matches it at longer horizons; "
        "monthly rainfall in Bangladesh is weakly predictable months ahead.",
        "- Dryness classes: the model rarely predicts the dry classes, so its macro-F1 is close to the climatology baseline. "
        "The risk class therefore leans on the engine's stress ratio (rule: level = max(stress, dryness)).",
        "- Interval coverage below the nominal 90% means the per-month residual intervals are too narrow on the test years.",
        "",
        "## Uncertainty and explainability",
        "90% intervals from 5th–95th percentiles of validation residuals per target month. SHAP TreeExplainer on the "
        "operational model: global mean |SHAP| over test rows and a local explanation of each division's latest forecast "
        "(ml/artifacts/shap.json).",
        "",
        "## Intended use and limits",
        "Decision support and education: indicating whether the coming months are likely drier or wetter than normal for a "
        "division. Not for operational drought declaration, not station-level, and not a forecast of water availability "
        "or groundwater. Under a What-if scenario the model is re-run with perturbed recent inputs plus the scenario's direct "
        "effect on the target month; that output is Simulated, not a forecast.",
    ]
    (ROOT / "docs" / "MODEL_CARD.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("docs/MODEL_CARD.md written")


if __name__ == "__main__":
    main()
