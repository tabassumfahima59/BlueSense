import AxeBuilder from "@axe-core/playwright";
import { expect, type Page, test } from "@playwright/test";

const sse = (events: object[]) => events.map((e) => `event: ${(e as { type: string }).type}\ndata: ${JSON.stringify(e)}\n\n`).join("");

test("without a server key the Copilot says it is not configured and accepts no questions", async ({ page }) => {
  // the e2e backend runs without any LLM key
  await page.goto("/copilot");
  await expect(page.getByTestId("copilot-status")).toHaveText("Not configured");
  const main = page.getByRole("main");
  await expect(main.getByText("The Copilot is not configured.")).toBeVisible();
  await expect(main.getByText(/gives no canned or rule-based answers/)).toBeVisible();
  await expect(main.getByLabel("Ask the Copilot")).toBeDisabled();
  await expect(main.getByRole("button", { name: "Send" })).toBeDisabled();
  await expect(main.getByRole("button", { name: /What is the weather in Dhaka/ })).toHaveCount(0);
  await expect(page.getByText("Read-only tools")).toBeVisible();
  const res = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa"]).analyze();
  expect(res.violations.map((v) => `${v.id}: ${v.nodes.map((n) => n.html.slice(0, 120)).join(" | ")}`)).toEqual([]);
});

/** UI behaviour with a configured server, using a recorded event stream (no LLM call is made). */
async function mockReady(page: Page, events: object[]) {
  await page.route("**/api/copilot/status", (r) => r.fulfill({ json: {
    status: "ready", provider: "gemini", providerLabel: "Google Gemini", model: "gemini-3.6-flash", reason: null, readOnly: true,
    disclosure: "Answers are generated by Google Gemini (free tier). Do not enter personal or sensitive information. For users aged 18 or over.",
    policyUrl: "https://ai.google.dev/gemini-api/terms", rateLimitPerMin: 5, streaming: true,
    limits: { perMinute: 5, perDay: 30, siteModelCallsPerDay: 200, siteModelCallsUsedToday: 3, maxConcurrent: 2, maxModelCallsPerQuestion: 4,
      resetsAt: "midnight Pacific time (about 1-2 pm in Bangladesh)" },
    tools: [{ name: "get_current_weather", description: "Current weather", module: "Command Center" }] } }));
  let body: Record<string, unknown> | null = null;
  await page.route("**/api/copilot/stream", (r) => {
    body = r.request().postDataJSON();
    return r.fulfill({ status: 200, headers: { "content-type": "text/event-stream" }, body: sse(events) });
  });
  return () => body;
}

test("a configured Copilot streams the answer, shows the data it used and flags unmatched numbers", async ({ page }) => {
  const sent = await mockReady(page, [
    { type: "delta", text: "Checking the weather. " },
    { type: "tool", status: "running", name: "get_current_weather" },
    { type: "tool", status: "done", name: "get_current_weather", module: "Command Center", input: { region: "dhaka" }, dataKind: ["model_current"] },
    { type: "delta", text: "Dhaka is 21 °C now [Command Center]; 98765 mm fell." },
    { type: "done", model: "gemini-3.6-flash", provider: "gemini", stopReason: "STOP", unverifiedNumbers: [98765],
      tools: [{ status: "done", name: "get_current_weather", module: "Command Center", input: { region: "dhaka" }, dataKind: ["model_current"] }] },
  ]);
  await page.goto("/copilot?region=dhaka");
  await expect(page.getByTestId("copilot-status")).toHaveText("Ready");
  const note = page.getByRole("main").getByTestId("copilot-disclosure");
  await expect(note).toContainText("AI provider: Google Gemini.");
  await expect(note).toContainText("Do not enter personal or sensitive information");
  await expect(note.getByRole("link", { name: "Provider terms" })).toHaveAttribute("href", "https://ai.google.dev/gemini-api/terms");
  await expect(page.getByText("5 / min · 30 / day")).toBeVisible();
  const box = page.getByRole("main").getByLabel("Ask the Copilot");
  await box.fill("How warm is it?");
  await box.press("Enter");
  const answer = page.getByTestId("copilot-answer").last();
  await expect(answer).toContainText("Checking the weather. Dhaka is 21 °C now [Command Center]");
  await expect(answer.getByRole("link", { name: /Current weather · dhaka · model_current/ })).toHaveAttribute("href", "/command-center");
  await expect(answer.getByText(/Check 98,765: not found in the data the Copilot looked up/)).toBeVisible();
  await expect(answer.getByText(/Generated by gemini-3\.6-flash from AquaGuard data/)).toBeVisible();
  const b = sent();
  expect(b).toMatchObject({ message: "How warm is it?", region: "dhaka" });
  expect(typeof (b as { clientId?: unknown }).clientId).toBe("string");
});

test("errors from the server are shown as errors, not as answers", async ({ page }) => {
  await mockReady(page, [{ type: "error", code: "refusal", detail: "The model declined to answer this request." }]);
  await page.goto("/copilot");
  const box = page.getByRole("main").getByLabel("Ask the Copilot");
  await box.fill("something");
  await box.press("Enter");
  await expect(page.getByTestId("copilot-answer").last().getByText("The model declined to answer this request.")).toBeVisible();
});

test("a used-up provider quota is shown as an error with the reset time", async ({ page }) => {
  await mockReady(page, [{ type: "error", code: "quota_exhausted",
    detail: "The AI service's free quota is used up for now. Per-minute limits clear within a minute; daily quotas reset at midnight Pacific time (about 1-2 pm in Bangladesh)." }]);
  await page.goto("/copilot");
  const box = page.getByRole("main").getByLabel("Ask the Copilot");
  await box.fill("anything");
  await box.press("Enter");
  await expect(page.getByTestId("copilot-answer").last().getByText(/free quota is used up/)).toBeVisible();
  await expect(page.getByTestId("copilot-answer").last().getByText(/Generated by/)).toHaveCount(0);
});
