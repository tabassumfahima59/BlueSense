"""Google Gemini adapter: REST ``models/{model}:streamGenerateContent?alt=sse`` over httpx (no extra package).

* The API key goes only in the ``x-goog-api-key`` header (never in a URL, log or error message).
* Model turns are kept exactly as received (every part, including ``thoughtSignature`` metadata and empty-text parts)
  and sent back unchanged, as Gemini requires for function calling with thinking models.
* Errors map to ``LLMError`` codes: quota (HTTP 429 / RESOURCE_EXHAUSTED), auth, unknown model, unavailable, timeout,
  blocked by the provider's safety filters, malformed output. No retry on quota errors; one retry when the service is
  briefly unavailable before anything was streamed.
"""
from __future__ import annotations

import json
import logging
import time
from collections.abc import Iterator
from typing import Any

import httpx

from .base import LLMError, ToolCall, ToolResult, ToolSpec, Turn

log = logging.getLogger("aquaguard.copilot.gemini")

BASE_URL = "https://generativelanguage.googleapis.com/v1beta"
DEFAULT_MODEL = "gemini-3.6-flash"
POLICY_URL = "https://ai.google.dev/gemini-api/terms"
DISCLOSURE = (
    "Answers are generated by Google Gemini (free tier). Your question and the AquaGuard data the Copilot looks up "
    "are sent to Google and processed under the Gemini API terms: on the free tier Google may use them to improve its "
    "products, and human reviewers may read them. Do not enter personal or sensitive information. For users aged 18 "
    "or over; the free tier may not be offered to users in the EEA, the UK or Switzerland.")
QUOTA_DETAIL = ("The AI service's free quota is used up for now. Per-minute limits clear within a minute; daily "
                "quotas reset at midnight Pacific time (about 1-2 pm in Bangladesh).")
BLOCKED = {"SAFETY", "RECITATION", "LANGUAGE", "BLOCKLIST", "PROHIBITED_CONTENT", "SPII", "IMAGE_SAFETY",
           "PUP_LIMITED_DISABLED"}
MALFORMED = {"MALFORMED_FUNCTION_CALL", "UNEXPECTED_TOOL_CALL", "TOO_MANY_TOOL_CALLS", "MISSING_THOUGHT_SIGNATURE",
             "MALFORMED_RESPONSE"}
GENERATED_ID = "_aquaguard_call_"


class GeminiProvider:
    name = "gemini"
    label = "Google Gemini"
    policy_url = POLICY_URL
    disclosure = DISCLOSURE

    def __init__(self, api_key: str, model: str, thinking_level: str = "low", timeout_s: float = 30.0,
                 transport: httpx.BaseTransport | None = None, base_url: str = BASE_URL):
        self._key = api_key
        self.model = model
        self.thinking_level = thinking_level
        self._url = f"{base_url}/models/{model}:streamGenerateContent?alt=sse"
        self._client = httpx.Client(timeout=httpx.Timeout(timeout_s, connect=10.0), transport=transport)

    def close(self) -> None:
        self._client.close()

    # ------------------------------------------------------------ conversation format

    def user_message(self, context: str, question: str) -> dict:
        return {"role": "user", "parts": [{"text": context}, {"text": question}]}

    def history_message(self, role: str, text: str) -> dict:
        return {"role": "model" if role == "assistant" else "user", "parts": [{"text": text}]}

    def tool_results_message(self, results: list[ToolResult]) -> dict:
        parts = []
        for r in results:
            try:
                data = json.loads(r.content)
            except ValueError:
                data = r.content
            fr: dict[str, Any] = {"name": r.call.name, "response": {"error": data} if r.is_error else {"result": data}}
            if not r.call.id.startswith(GENERATED_ID):
                fr["id"] = r.call.id
            parts.append({"functionResponse": fr})
        return {"role": "user", "parts": parts}

    # ------------------------------------------------------------ one streamed model call

    def _body(self, system: str, messages: list, tools: list[ToolSpec], max_tokens: int) -> dict:
        body: dict[str, Any] = {
            "systemInstruction": {"parts": [{"text": system}]},
            "contents": messages,
            "tools": [{"functionDeclarations": [{"name": t.name, "description": t.description,
                                                 "parametersJsonSchema": t.schema} for t in tools]}],
            "toolConfig": {"functionCallingConfig": {"mode": "AUTO"}},
            "generationConfig": {"maxOutputTokens": max_tokens},
        }
        if self.thinking_level:
            body["generationConfig"]["thinkingConfig"] = {"thinkingLevel": self.thinking_level}
        return body

    def _error(self, status: int, payload: Any) -> LLMError:
        err = payload.get("error", {}) if isinstance(payload, dict) else {}
        state = str(err.get("status") or "")
        message = str(err.get("message") or "")[:300]
        log.warning("gemini API error: HTTP %s %s %s", status, state, message)
        if status == 429 or state == "RESOURCE_EXHAUSTED":
            return LLMError("quota_exhausted", QUOTA_DETAIL)
        if status in (401, 403) or state in ("UNAUTHENTICATED", "PERMISSION_DENIED"):
            return LLMError("llm_auth", "The server's Gemini API key was rejected or lacks access.")
        if status == 404:
            return LLMError("llm_config", f"The configured Gemini model '{self.model}' was not found.")
        if status >= 500:
            return LLMError("llm_unavailable", "The AI service is temporarily unavailable. Try again shortly.")
        if "location" in message.lower() and "not supported" in message.lower():
            return LLMError("llm_config", "The AI service is not available from the server's location.")
        return LLMError("llm_error", f"The AI service rejected the request ({state or status}).")

    def _open(self, body: dict):
        headers = {"x-goog-api-key": self._key, "Content-Type": "application/json", "Accept": "text/event-stream"}
        for attempt in (1, 2):
            cm = self._client.stream("POST", self._url, headers=headers, json=body)
            try:
                resp = cm.__enter__()
            except httpx.TimeoutException:
                if attempt == 2:
                    raise LLMError("llm_timeout", "The AI service did not respond in time.") from None
                continue
            except httpx.TransportError:
                if attempt == 2:
                    raise LLMError("llm_unavailable", "The AI service could not be reached.") from None
                time.sleep(1.0)
                continue
            if resp.status_code in (500, 502, 503, 504) and attempt == 1:
                resp.read()
                cm.__exit__(None, None, None)
                time.sleep(1.0)
                continue
            return cm, resp
        raise LLMError("llm_unavailable", "The AI service could not be reached.")

    def stream_turn(self, system: str, messages: list, tools: list[ToolSpec],
                    max_tokens: int) -> Iterator[str | Turn]:
        cm, resp = self._open(self._body(system, messages, tools, max_tokens))
        parts: list[dict] = []
        finish: str | None = None
        model_version: str | None = None
        try:
            if resp.status_code >= 400:
                resp.read()
                try:
                    payload = resp.json()
                except ValueError:
                    payload = None
                raise self._error(resp.status_code, payload)
            for line in resp.iter_lines():
                if not line.startswith("data:"):
                    continue
                data = line[5:].strip()
                if not data:
                    continue
                try:
                    chunk = json.loads(data)
                except ValueError:
                    raise LLMError("llm_error", "The AI service sent an unreadable response.") from None
                if isinstance(chunk, dict) and chunk.get("error"):
                    raise self._error(int(chunk["error"].get("code") or 500), chunk)
                block = (chunk.get("promptFeedback") or {}).get("blockReason")
                if block:
                    raise LLMError("refusal", f"The AI provider blocked this request ({block}).")
                model_version = chunk.get("modelVersion") or model_version
                cands = chunk.get("candidates") or []
                if not cands:
                    continue
                cand = cands[0]
                for part in (cand.get("content") or {}).get("parts") or []:
                    parts.append(part)  # kept exactly as received
                    text = part.get("text")
                    if text and not part.get("thought"):
                        yield text
                finish = cand.get("finishReason") or finish
        except httpx.TimeoutException:
            raise LLMError("llm_timeout", "The AI service stopped responding.") from None
        except httpx.TransportError:
            raise LLMError("llm_unavailable", "The connection to the AI service was lost.") from None
        finally:
            cm.__exit__(None, None, None)

        if finish in BLOCKED:
            raise LLMError("refusal", f"The AI provider blocked this answer ({finish}).")
        if finish in MALFORMED:
            raise LLMError("model_error", f"The AI model returned an invalid tool call ({finish}).")
        calls = [p["functionCall"] for p in parts if isinstance(p.get("functionCall"), dict)]
        if not parts and not finish:
            raise LLMError("llm_error", "The AI service returned an empty response.")
        if calls and finish == "MAX_TOKENS":
            raise LLMError("truncated", "The answer was cut off. Ask a narrower question.")
        assistant = {"role": "model", "parts": parts}
        if calls:
            return_calls = [ToolCall(id=str(c.get("id") or f"{GENERATED_ID}{i}"), name=str(c.get("name") or ""),
                                     args=c.get("args") if c.get("args") is not None else {})
                            for i, c in enumerate(calls)]
            yield Turn(stop="tool_calls", tool_calls=return_calls, assistant=assistant, model=model_version or self.model)
            return
        yield Turn(stop="end", assistant=assistant, model=model_version or self.model, finish=finish)
