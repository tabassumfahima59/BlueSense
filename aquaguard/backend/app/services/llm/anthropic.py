"""Anthropic Claude adapter (the M8 implementation, moved behind the provider interface unchanged).

``client.beta.messages.stream`` with eager input streaming, effort ``medium``, the server-side refusal fallback on
models that accept it, and the assistant content appended back unchanged."""
from __future__ import annotations

from collections.abc import Iterator
from typing import Any

from .base import LLMError, ToolCall, ToolResult, ToolSpec, Turn

DEFAULT_MODEL = "claude-opus-5-5"
FALLBACK_MODELS = {"claude-opus-5-5", "claude-opus-5", "claude-fable-5-2", "claude-fable-5-1", "claude-sonnet-5-5"}
FALLBACK_BETA = "server-side-fallback-2026-07-01"
EFFORT = "medium"
POLICY_URL = "https://www.anthropic.com/legal/commercial-terms"
DISCLOSURE = ("Answers are generated by Anthropic Claude. Your question and the AquaGuard data the Copilot looks up are "
              "sent to Anthropic and processed under Anthropic's API terms and privacy policy. Do not enter personal "
              "or sensitive information.")


class AnthropicProvider:
    name = "anthropic"
    label = "Anthropic Claude"
    policy_url = POLICY_URL
    disclosure = DISCLOSURE

    def __init__(self, client: Any, model: str):
        self.client = client
        self.model = model

    def close(self) -> None:
        close = getattr(self.client, "close", None)
        if callable(close):
            close()

    def user_message(self, context: str, question: str) -> dict:
        return {"role": "user", "content": [{"type": "text", "text": context}, {"type": "text", "text": question}]}

    def history_message(self, role: str, text: str) -> dict:
        return {"role": role, "content": text}

    def tool_results_message(self, results: list[ToolResult]) -> dict:
        return {"role": "user", "content": [{"type": "tool_result", "tool_use_id": r.call.id, "content": r.content,
                                             "is_error": r.is_error} for r in results]}

    def _kwargs(self, system: str, tools: list[ToolSpec], max_tokens: int) -> dict:
        kwargs: dict = {"model": self.model, "max_tokens": max_tokens, "system": system,
                        "tools": [{"name": t.name, "description": t.description, "input_schema": t.schema,
                                   "eager_input_streaming": True} for t in tools],
                        "output_config": {"effort": EFFORT}, "cache_control": {"type": "ephemeral"}}
        if self.model in FALLBACK_MODELS:
            kwargs.update(betas=[FALLBACK_BETA], fallbacks="default")
        return kwargs

    def stream_turn(self, system: str, messages: list, tools: list[ToolSpec],
                    max_tokens: int) -> Iterator[str | Turn]:
        import anthropic

        kwargs = self._kwargs(system, tools, max_tokens)
        json_retries = 0
        while True:
            try:
                with self.client.beta.messages.stream(messages=messages, **kwargs) as stream:
                    for text in stream.text_stream:
                        yield text
                    response = stream.get_final_message()
                break
            except ValueError:
                # tool-input JSON the SDK could not parse at all (eager input streaming): re-issue, bounded
                json_retries += 1
                if json_retries > 2:
                    raise LLMError("model_error", "The model returned unreadable tool input.") from None
            except anthropic.RateLimitError:
                raise LLMError("llm_rate_limited", "The LLM service is busy. Try again shortly.") from None
            except anthropic.AuthenticationError:
                raise LLMError("llm_auth", "The server's LLM API key was rejected.") from None
            except anthropic.APITimeoutError:
                raise LLMError("llm_timeout", "The AI service did not respond in time.") from None
            except anthropic.APIConnectionError:
                raise LLMError("llm_unavailable", "The LLM service could not be reached.") from None
            except anthropic.APIStatusError as e:
                if e.status_code in (500, 502, 503, 529):
                    raise LLMError("llm_unavailable", "The AI service is temporarily unavailable.") from None
                raise LLMError("llm_error", f"The LLM service returned an error ({e.status_code}).") from None

        if response.stop_reason == "refusal":
            raise LLMError("refusal", "The model declined to answer this request.")
        model = getattr(response, "model", self.model)
        assistant = {"role": "assistant", "content": response.content}
        if response.stop_reason == "pause_turn":
            yield Turn(stop="pause", assistant=assistant, model=model, finish="pause_turn")
            return
        uses = [b for b in response.content if b.type == "tool_use"]
        if not uses:
            yield Turn(stop="end", assistant=assistant, model=model, finish=response.stop_reason)
            return
        if response.stop_reason == "max_tokens":
            raise LLMError("truncated", "The answer was cut off. Ask a narrower question.")
        yield Turn(stop="tool_calls", tool_calls=[ToolCall(id=b.id, name=b.name, args=b.input) for b in uses],
                   assistant=assistant, model=model, finish=response.stop_reason)
